#!/usr/bin/env python3
"""Real end-to-end Build 02 test (NOT executed in this offline sandbox).

Prerequisites: Docker stack healthy, Playwright+Chromium installed.
This test MUTATES the development database. Run only on a disposable local stack:
  docker compose down -v   # DANGER: deletes all local stack data
  docker compose up --build -d
  python3 scripts/e2e_creator_live.py

Demo credentials are intentionally development-only and must never be deployed publicly.
"""
import asyncio
from datetime import date, timedelta
from pathlib import Path
from playwright.async_api import async_playwright

BASE = 'http://localhost:3000'
ROOT = Path(__file__).resolve().parents[1]

async def login(page, button: str, username: str, password: str):
    await page.get_by_role('button', name=button).click()
    await page.locator('#username').fill(username)
    await page.locator('#password').fill(password)
    await page.locator('#kc-login').click()
    # Keycloak's OIDC callback is a separate route; navigate to desired panel after it finishes.
    await page.wait_for_url('**/auth/callback*', timeout=30000)
    await page.wait_for_timeout(1500)

async def main():
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)
        creator_ctx = await browser.new_context()
        creator = await creator_ctx.new_page()
        await creator.goto(BASE + '/creator')
        await login(creator, 'Sign in to Creator Studio', 'demo', 'DemoOnly123!')
        await creator.goto(BASE + '/creator')
        await creator.get_by_label('Display name').fill('Test Independent Pictures')
        await creator.get_by_label('Legal name').fill('Test Creator')
        await creator.get_by_label('Contact email').fill('demo-creator@example.invalid')
        await creator.get_by_label('Describe your work and rights to distribute it').fill(
            'This is an original local test video generated by the ReelNest repository.')
        await creator.get_by_role('button', name='Submit application').click()
        await creator.get_by_text('PENDING', exact=True).wait_for()

        admin_ctx = await browser.new_context()
        admin = await admin_ctx.new_page()
        await admin.goto(BASE + '/admin')
        await login(admin, 'Sign in as reviewer', 'reviewer', 'LocalReviewer123!')
        await admin.goto(BASE + '/admin')
        await admin.get_by_role('button', name='Approve', exact=True).first.click()
        await admin.get_by_text('Creator approved.').wait_for()

        await creator.reload()
        await creator.get_by_label('Film title').fill('Original Local Media Test')
        await creator.get_by_label('Synopsis').fill('An original short clip created as a software integration test.')
        await creator.get_by_label('Duration (minutes)').fill('1')
        await creator.get_by_role('button', name='Create draft').click()
        await creator.get_by_text('Draft created.').wait_for()
        today = date.today()
        await creator.get_by_label('Valid from').fill(str(today))
        await creator.get_by_label('Valid until').fill(str(today + timedelta(days=365)))
        await creator.get_by_label('Rights evidence reference').fill('Internal original-video generator, scripts/generate_demo_media.sh')
        await creator.get_by_label('Agreement notes').fill('I grant development-only testing access to the original ReelNest-generated sample video.')
        await creator.get_by_role('button', name='Save rights').click()
        await creator.get_by_text('Rights declaration saved.').wait_for()
        await creator.locator('input[type="file"]').set_input_files(str(ROOT/'apps/web/public/sample/demo.mp4'))
        await creator.get_by_role('button', name='Upload securely').click()
        await creator.get_by_text('Video uploaded to private storage.').wait_for(timeout=120000)
        await creator.get_by_role('button', name='Submit film for review').click()
        await creator.get_by_text('Sent to administrator review.').wait_for()
        await admin.reload()
        await admin.get_by_role('button', name='Inspect rights').first.click()
        await admin.get_by_role('button', name='Approve rights').first.click()
        await admin.get_by_text('Rights approved.').wait_for()
        # Build 02 has no general transcoder. Approving rights MUST NOT enable direct publication.
        await admin.get_by_role('button', name='Attempt publish').first.click()
        await admin.get_by_role('alert').get_by_text('409', exact=False).wait_for()
        print('PASS: creator approval -> title -> rights -> multipart upload -> review; premature publish rejected')
        await browser.close()

if __name__ == '__main__':
    asyncio.run(main())
