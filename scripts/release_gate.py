"""Reproducible release evidence report. Never mistakes offline checks for production readiness.

Usage:
 python3 scripts/release_gate.py --mode offline --output docs/BUILD10_CHECK_RESULTS.json
 python3 scripts/release_gate.py --mode production --output release-results.json

Production mode is intentionally blocked until reviewed external evidence exists.
An attestation is a checklist from a human operator, not independent verification.
"""
